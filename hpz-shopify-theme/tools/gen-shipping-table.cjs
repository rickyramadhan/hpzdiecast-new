// Turns the shipping zones/rates of a store (Admin API via `shopify store execute`) into snippets/shipping-rates-data.liquid,
// a JSON blob the product page uses to estimate shipping per country and weight without any API token.
// Re-run whenever the shipping rates change:
//   node tools/gen-shipping-table.cjs <store.myshopify.com>      (store must be authorised with read_shipping)
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const store = process.argv[2];
if (!store) { console.error('usage: node tools/gen-shipping-table.cjs <store.myshopify.com>'); process.exit(1); }
const QA = path.resolve(__dirname, '../../.qa');
const q = path.join(QA, '_ship.graphql'), o = path.join(QA, '_ship.json');
fs.writeFileSync(q, `query { deliveryProfiles(first: 10) { nodes { name default profileLocationGroups { locationGroupZones(first: 50) { nodes {
  zone { name countries { code { countryCode restOfWorld } } }
  methodDefinitions(first: 20) { nodes { name active rateProvider { __typename ... on DeliveryRateDefinition { price { amount currencyCode } } }
    methodConditions { field operator conditionCriteria { __typename ... on MoneyV2 { amount } ... on Weight { unit value } } } } } } } } } } }`);
try { fs.unlinkSync(o); } catch (e) {}
spawnSync('shopify', ['store', 'execute', '-s', store, '--query-file', q, '--json', '--output-file', o], { shell: true, env: Object.assign({}, process.env, { MSYS_NO_PATHCONV: '1' }) });
if (!fs.existsSync(o)) { console.error('query failed (authorise first: shopify store auth -s ' + store + ' --scopes read_shipping)'); process.exit(1); }
const j = JSON.parse(fs.readFileSync(o, 'utf8')); const d = j.data || j;
const toKg = c => (c.unit === 'GRAMS' ? c.value / 1000 : c.unit === 'POUNDS' ? c.value * 0.45359237 : c.unit === 'OUNCES' ? c.value * 0.0283495 : c.value);
const zones = [];
for (const p of d.deliveryProfiles.nodes) {
  if (!p.default) continue; // other profiles would need their own handling, shown as "calculated at checkout"
  for (const g of p.profileLocationGroups) for (const z of g.locationGroupZones.nodes) {
    const countries = z.zone.countries.map(c => c.code.countryCode).filter(c => c && c !== 'ID'); // Indonesia is served by its own store
    const byName = {};
    for (const m of z.methodDefinitions.nodes) {
      if (!m.active || m.rateProvider.__typename !== 'DeliveryRateDefinition') continue;
      const w = m.methodConditions.filter(c => c.field === 'TOTAL_WEIGHT');
      const price = m.methodConditions.filter(c => c.field === 'TOTAL_PRICE');
      if (price.length) continue; // price-based tiers are not estimated here
      let min = 0, max = null;
      for (const c of w) {
        const v = c.conditionCriteria.value == null ? null : toKg(c.conditionCriteria);
        if (/GREATER/.test(c.operator) && v != null) min = v;
        if (/LESS/.test(c.operator) && v != null) max = v;
      }
      (byName[m.name] = byName[m.name] || []).push({ min: +min.toFixed(4), max: max == null ? null : +max.toFixed(4), price: +m.rateProvider.price.amount, cur: m.rateProvider.price.currencyCode });
    }
    const methods = Object.keys(byName).map(n => ({ name: n, tiers: byName[n].sort((a, b) => a.min - b.min) }));
    if (countries.length && methods.length) zones.push({ zone: z.zone.name, countries, methods });
  }
}
const out = `{%- comment -%} Generated by tools/gen-shipping-table.cjs from the store's shipping zones. Do not edit by hand; re-run the tool when rates change. {%- endcomment -%}\n` + JSON.stringify({ generated: new Date().toISOString().slice(0, 10), zones });
fs.writeFileSync(path.resolve(__dirname, '../snippets/shipping-rates-data.liquid'), out);
console.log('zones', zones.length, zones.map(z => z.zone + ':' + z.countries.length + 'c/' + z.methods.length + 'm').join('  '));
