// Generates snippets/default-castings-list.liquid (delimited records for Liquid loops) from the JSON fallback
// in snippets/default-castings.liquid. Liquid has no parse_json filter, so loops read delimited text instead.
// Record format (one line, records joined by ";;", fields by "|"):
//   handle|name|maker|year|body|dia|axle|kw1,kw2
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, '../snippets/default-castings.liquid'), 'utf8');
const json = src.slice(src.indexOf('[\n') >= 0 ? src.indexOf('[\n') : src.indexOf('['));
const list = JSON.parse(json);
const rec = c => [c.handle, c.name, c.maker, c.year, c.body, c.dia, c.axle, (c.match || []).join(',')].join('|');
const out = [
  '{%- comment -%}',
  '  Generated by tools/gen-castings.cjs from default-castings.liquid. Do not edit by hand.',
  '  Delimited fallback casting list for Liquid loops (there is no parse_json filter).',
  '  Usage:',
  "    {%- capture raw -%}{%- render 'default-castings-list' -%}{%- endcapture -%}",
  "    {%- assign recs = raw | strip | split: ';;' -%}",
  "    {%- for r in recs -%}{%- assign c = r | split: '|' -%} c[0]=handle c[1]=name c[2]=maker c[3]=year c[4]=body c[5]=dia c[6]=axle c[7]=keywords (comma list) {%- endfor -%}",
  '{%- endcomment -%}',
  list.map(rec).join(';;'),
];
fs.writeFileSync(path.join(__dirname, '../snippets/default-castings-list.liquid'), out.join('\n') + '\n');
console.log('castings:', list.length);
