// Extracts the SVG icons from the mockup (hpz-redesign/assets/js/core.js) into snippets/icon.liquid,
// and patches the WhatsApp glyph in assets/theme.js so both stay identical. Re-run after changing the mockup.
const fs = require('fs'), path = require('path');
const core = fs.readFileSync(path.join(__dirname, '../../hpz-redesign/assets/js/core.js'), 'utf8');
// only the ICON object (FLAG has its own SVGs, which we do not want here)
const all = core.split('\n');
const start = all.findIndex(l => /^\s{2}const ICON = \{/.test(l));
const end = all.findIndex((l, i) => i > start && /^\s{2}\};/.test(l));
const lines = all.slice(start + 1, end);

// 1) path icons: name: I('<paths>')
const pathIcons = {};
for (const line of lines) {
  const m = line.match(/^\s{4}(\w+): I\('(.*)'(?:, '[^']*')?\),?\s*$/);
  if (m) pathIcons[m[1]] = m[2];
}
// 2) raw SVG icons: name: '<svg ...>...</svg>' (wa, star, ...)
const rawIcons = {};
for (const line of lines) {
  const m = line.match(/^\s{4}(\w+): '(<svg.*)',?\s*$/);
  if (m) rawIcons[m[1]] = m[2];
}

for (const [k, d] of Object.entries(pathIcons)) if (d.includes("'")) throw new Error('apostrophe in icon ' + k);
for (const [k, d] of Object.entries(rawIcons)) if (d.includes("'")) throw new Error('apostrophe in raw icon ' + k);

const out = [
  '{%- comment -%}',
  "  Usage: {% render 'icon', name: 'cart' %}",
  '  Shared icon set, generated by tools/gen-icons.cjs from the mockup. Do not edit by hand.',
  '{%- endcomment -%}',
  '{%- liquid',
  "  assign svg_open = '<svg viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"1.6\" stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\">'",
  '  case name',
];
for (const [k, d] of Object.entries(pathIcons)) {
  out.push('  when "' + k + '"', '    echo svg_open', "    echo '" + d + "'", "    echo '</svg>'");
}
for (const [k, d] of Object.entries(rawIcons)) {
  out.push('  when "' + k + '"', "    echo '" + d + "'");
}
out.push('  endcase', '-%}');
fs.writeFileSync(path.join(__dirname, '../snippets/icon.liquid'), out.join('\n') + '\n');

// WhatsApp glyph for the JS side (theme.js mirrors the Liquid icon set)
const wa = rawIcons.wa;
if (wa) {
  const jsPath = path.join(__dirname, '../assets/theme.js');
  let js = fs.readFileSync(jsPath, 'utf8');
  js = js.replace(/    wa: .*\n/, '    wa: ' + JSON.stringify(wa) + ',\n');
  fs.writeFileSync(jsPath, js);
}
console.log('path icons:', Object.keys(pathIcons).length, 'raw icons:', Object.keys(rawIcons).join(','));
